package roofsense.entities;

/**
 * Represents the orientation of a measurement point according to cardinal and intercardinal directions.
 */
public enum Orientation {

    /**
     * North orientation.
     */
    N,

    /**
     * North-East orientation.
     */
    NE,

    /**
     * East orientation.
     */
    E,

    /**
     * South-East orientation.
     */
    SE,

    /**
     * South orientation.
     */
    S,

    /**
     * South-West orientation.
     */
    SW,

    /**
     * West orientation.
     */
    W,

    /**
     * North-West orientation.
     */
    NW
}
